use super::*;
use std::{fs, io::Write};
#[test]
fn native_sources_and_retained_parents_bind_complete_content_and_identity() {
    let temp = tempfile::tempdir().unwrap();
    let path = temp.path().canonicalize().unwrap();
    let root = Dir::open(&path).unwrap();
    let input = root.mkdir("source").unwrap();
    input
        .create("pack.zip")
        .unwrap()
        .write_all(b"synthetic source")
        .unwrap();
    let first = hash_file(input.regular("pack.zip").unwrap(), MAX_BYTES, None).unwrap();
    assert_eq!(
        first.hash,
        format!("{:x}", Sha256::digest(b"synthetic source"))
    );
    let held = input.regular("pack.zip").unwrap();
    fs::rename(path.join("source"), path.join("held-source")).unwrap();
    let replacement = root.mkdir("source").unwrap();
    replacement
        .create("pack.zip")
        .unwrap()
        .write_all(b"different bytes")
        .unwrap();
    assert_eq!(hash_file(held, MAX_BYTES, None).unwrap(), first);
    assert_ne!(
        hash_file(replacement.regular("pack.zip").unwrap(), MAX_BYTES, None).unwrap(),
        first
    );
}
#[test]
fn native_no_replace_directory_move_preserves_both_originals_on_collision() {
    let temp = tempfile::tempdir().unwrap();
    let path = temp.path().canonicalize().unwrap();
    let root = Dir::open(&path).unwrap();
    let a = root.mkdir("a").unwrap();
    let b = root.mkdir("b").unwrap();
    a.create("original")
        .unwrap()
        .write_all(b"source bytes")
        .unwrap();
    b.create("original")
        .unwrap()
        .write_all(b"destination bytes")
        .unwrap();
    assert!(move_new(&root, "a", &root, "b").is_err());
    assert_eq!(fs::read(path.join("a/original")).unwrap(), b"source bytes");
    assert_eq!(
        fs::read(path.join("b/original")).unwrap(),
        b"destination bytes"
    );
}
#[cfg(unix)]
#[test]
fn native_sources_and_descendants_refuse_literal_symlinks() {
    let temp = tempfile::tempdir().unwrap();
    let path = temp.path().canonicalize().unwrap();
    let root = Dir::open(&path).unwrap();
    let input = root.mkdir("source").unwrap();
    input
        .create("kept")
        .unwrap()
        .write_all(b"original")
        .unwrap();
    std::os::unix::fs::symlink(path.join("source"), path.join("alias")).unwrap();
    std::os::unix::fs::symlink(path.join("source/kept"), path.join("leaf")).unwrap();
    assert!(root.child("alias").is_err());
    assert!(root.regular("leaf").is_err());
    assert_eq!(fs::read(path.join("source/kept")).unwrap(), b"original");
}
#[test]
fn registered_stage_publishes_only_its_allocated_literal_target() {
    let temp = tempfile::tempdir().unwrap();
    let path = temp.path().canonicalize().unwrap();
    let root = Dir::open(&path).unwrap();
    let inputs = root.mkdir("inputs").unwrap().with_input_sources().unwrap();
    let mut file = inputs.stage_for("owned-output", 1024).unwrap();
    file.write_all(b"verified generated bytes").unwrap();
    let expected = hash_file(file.try_clone().unwrap(), 1024, None).unwrap();
    link_anonymous(&mut file, &inputs, "owned-output").unwrap();
    let output = hash_file(inputs.regular("owned-output").unwrap(), 1024, None).unwrap();
    assert!(expected.owned_matches(&output));
    assert_eq!(
        fs::read(path.join("inputs/owned-output")).unwrap(),
        b"verified generated bytes"
    );
    let mut wrong = inputs.stage_for("allocated-only", 1024).unwrap();
    wrong.write_all(b"never retarget").unwrap();
    assert!(link_anonymous(&mut wrong, &inputs, "different-leaf").is_err());
    assert!(!path.join("inputs/different-leaf").exists());
    assert!(!path.join("inputs/allocated-only").exists());
    let report = inputs.1.as_ref().unwrap().report().unwrap();
    assert!(
        report.pending_tickets >= 1,
        "unpublished registered source evidence is retained"
    );
}
#[test]
fn registered_inputs_share_one_process_area_and_discard_returns_pending_quota() {
    let temp = tempfile::tempdir().unwrap();
    let path = temp.path().canonicalize().unwrap();
    let root = Dir::open(&path).unwrap();
    let input = root.mkdir("inputs").unwrap();
    let first = input.with_input_sources().unwrap();
    let second = input.with_input_sources().unwrap();
    let mut a = first.stage_for("a", 1024).unwrap();
    let mut b = second.stage_for("b", 1024).unwrap();
    a.write_all(b"partial a").unwrap();
    b.write_all(b"partial b").unwrap();
    assert!(is_anonymous(&a).unwrap());
    assert!(is_anonymous(&b).unwrap());
    assert_eq!(
        first.1.as_ref().unwrap().report().unwrap().pending_tickets,
        2
    );
    drop(a);
    first.check_source_cleanup().unwrap();
    assert_eq!(
        first.1.as_ref().unwrap().report().unwrap().pending_tickets,
        1
    );
    drop(b);
    second.check_source_cleanup().unwrap();
    assert_eq!(
        first.1.as_ref().unwrap().report().unwrap().pending_tickets,
        0
    );
    assert!(!path.join("inputs/a").exists());
    assert!(!path.join("inputs/b").exists());
}
#[test]
fn native_journal_opaque_snapshot_rejects_external_generation_and_accounts_exact_auxiliaries() {
    let temp = tempfile::tempdir().unwrap();
    let path = temp.path().canonicalize().unwrap();
    let root = Dir::open(&path).unwrap();
    let directory = root.mkdir("operation").unwrap();
    let first = directory.with_journal().unwrap();
    first.write_journal_bytes(b"first generation").unwrap();
    let second = directory.with_journal().unwrap();
    second.write_journal_bytes(b"external generation").unwrap();
    assert!(first.write_journal_bytes(b"must not overwrite").is_err());
    assert_eq!(
        second.read_journal_bytes("journal.json").unwrap(),
        b"external generation"
    );
    assert_eq!(second.names().unwrap(), ["journal.json"]);
    directory
        .create("unknown-evidence")
        .unwrap()
        .write_all(b"preserved")
        .unwrap();
    assert!(second
        .names()
        .unwrap()
        .contains(&"unknown-evidence".to_string()));
    assert_eq!(
        fs::read(path.join("operation/unknown-evidence")).unwrap(),
        b"preserved"
    );
}
